"""Run the pipeline on the normal and the stress log; write results/metrics.json + results/process_model.md."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent / "src"))
from pminer.evaluate import run_all  # noqa: E402
from pminer.generate import STRESS, GenConfig  # noqa: E402

SHOW = ["n_raw_labels", "n_clusters", "noise_precision", "noise_recall", "label_accuracy",
        "edge_precision", "edge_recall", "extra_edges", "missing_edges", "fitness", "raw_label_sequences",
        "discovered_variants_no_mapping", "true_variants", "rule_acc_heldout_cases", "heldout_label_accuracy"]

if __name__ == "__main__":
    res = {"normal": run_all(GenConfig()), "stress": run_all(STRESS)}
    out = Path(__file__).parent / "results"
    out.mkdir(exist_ok=True)
    (out / "metrics.json").write_text(json.dumps(res, indent=2, default=str))
    m = res["normal"]
    lines = ["# Discovered process (auto-generated by run.py, normal log)", "",
             "## Decision rule for Manager approval", "```", m["rule_text"].rstrip(), "```", "", "## Top variants"]
    lines += [f"- {k} cases: {v}" for v, k in m["top_variants"]]
    lines += ["", "## Stress log decision rule", "```", res["stress"]["rule_text"].rstrip(), "```"]
    (out / "process_model.md").write_text("\n".join(lines) + "\n")
    for name, r in res.items():
        print(f"== {name}")
        for k in SHOW:
            print(f"  {k}: {r[k]}")
        print("  held-out misses:", [(x['raw_label'], x['predicted']) for x in r["heldout_misses"]])
